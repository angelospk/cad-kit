def pen_table() -> str:
    by_color = collections.defaultdict(list)
    for name, color, lw, _ in build.HER_LAYERS + build.KIT_LAYERS:
        by_color[color].append(name)
    pens = {s: build.pens(s) for s in build.SCALES}
    special = {**{c: "κόκκινο" for c in build.RED_PENS}, **{c: "γκρι 40%" for c in build.GRAY_PENS},
               **{c: "το χρώμα του" for c in build.OWN_COLOUR_PENS}}
    rows = ["| Χρώμα | 1:25 | 1:50 | 1:100 | Τυπώνεται | Layers |", "|---|---|---|---|---|---|"]
    for color in sorted(pens["50"], key=lambda c: (-pens["50"][c], c)):
        layers = ", ".join(f"`{n}`" for n in by_color.get(color, [])) or "-"
        rows.append(f"| {color} | {pens['25'][color]:.2f} | {pens['50'][color]:.2f} | {pens['100'][color]:.2f} "
                    f"| {special.get(color, 'μαύρο')} | {layers} |")
    return "\n".join(rows)


def layer_table() -> str:
    rows = ["| Layer | Χρώμα | Πάχος | Από |", "|---|---|---|---|"]
    for group, origin in ((build.HER_LAYERS, "δικό σου"), (build.KIT_LAYERS, "νέο")):
        for name, color, lw, ltype in group:
            width = "default" if lw < 0 else f"{lw / 100:.2f}"
            rows.append(f"| `{name}` | {color} | {width} | {origin} |")
    rows.append(f"| `{build.INFO_LAYER}` | 140 | default | νέο, δεν τυπώνεται |")
    return "\n".join(rows)


def write() -> pathlib.Path:
    text = HEAD + "\n## Layers\n\nΤα δικά σου layers μπήκαν με τα χρώματα και τα πάχη που έχουν στα 3 σχέδια που έστειλες.\n\n"
    text += layer_table()
    text += ("\n\n## Πένες (CTB)\n\nΤο πάχος στο 1:50 είναι το πάχος που έχουν ήδη τα layers σου. Στο 1:25 ανεβαίνει ένα βήμα, "
             "στο 1:100 κατεβαίνει. Οι ετικέτες, οι διαστάσεις και τα ηλεκτρολογικά κρατούν το ίδιο πάχος σε κάθε κλίμακα, "
             "γιατί έχουν το ίδιο μέγεθος στο χαρτί.\n\n"
             "Χρώμα που δεν είναι στον πίνακα τυπώνεται μαύρο, με το πάχος του layer του. "
             "Αντικείμενο με true color (RGB) τυπώνεται στο χρώμα του: έτσι βγαίνει το ξύλο στις πόρτες.\n\n")
    text += pen_table() + "\n" + TAIL
    path = ROOT / "out" / "ODIGIES.md"
    path.write_text(text, encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write())
